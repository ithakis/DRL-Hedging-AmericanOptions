"""LaTeX tabulars and figures of the revised paper (v2) from the FINAL results (adi_trading market family only:
validation seed 2025, test seed 4242). Writes review/results/paper/{tables,figures}/ (same paths as the paper's \\gendir).
Rule (a) (no band, w = 0) is tuned here on validation with the same grid as rule (b).
    PYTHONPATH=. python review/final/paper_tables_v2.py [FINAL_LOGS]"""
import itertools
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

from review.retrain import analysis as A
from review.retrain.settings import COSTS

FIN = Path("review/results/final")
OUT = Path("review/results/paper")
LOGS = Path(sys.argv[1] if len(sys.argv) > 1 else "../DRL-Hedging-AmericanOptions/logs_torch/final")
HEADER = "% generated by review/final/paper_tables_v2.py from review/results/final -- do not edit\n"
f2 = lambda x: f"{x:.2f}"
cl = lambda c: f"{c * 100:g}\\%"
ROB = {"init_vol": "$\\sqrt{v_0}=%s$", "volvol": "$\\xi=%s$", "rho": "$\\rho=%s$", "theta": "$\\theta=%s$",
       "kappa": "$\\kappa=%s$"}


def mk(seed):
    a = A.block_args("B", ["--market_dir", "../DRL-Hedging-retrain/markets", "--pricing_backend", "adi_trading",
                           "--table_dir", "../DRL-Hedging-retrain/pricing_tables"])
    return A.T.get_market(a, seed, 8192)


def rule_a(val, test):
    """Rule (a) = fraction rule without band, tuned on validation (a, b in 0..1 step 0.1, w = 0)."""
    P = test["S"].shape[0]
    idx = np.random.default_rng(7).integers(0, P, (1000, P))
    out = {}
    for c in COSTS:
        best = (np.inf, None)
        for a_, b_ in itertools.product(np.round(np.arange(0, 1.01, 0.1), 2), repeat=2):
            v = A.var_cvar(A.net(A.rollout(val, A.rule_decider("rule", a_, b_, 0.0), True), c))[0]
            best = min(best, (float(v), (float(a_), float(b_))))
        r = A.rollout(test, A.rule_decider("rule", *best[1], 0.0), True)
        p = A.net(r, c)
        v, cv = A.var_cvar(p)
        out[c] = dict(a=best[1][0], b=best[1][1], val_VaR95=best[0], VaR95=float(v),
                      VaR95_se=float(A.var_cvar(p[idx])[0].std(ddof=1)), CVaR95=float(cv),
                      CVaR95_se=float(A.var_cvar(p[idx])[1].std(ddof=1)), mean_pnl=float(p.mean()),
                      mean_cost=float(c * r["ob"].mean()))
        print("rule (a)", c, out[c], flush=True)
    return out


def heston_table(ra):
    ft = pd.read_csv(FIN / "final_table.csv")
    heads = ["Delta", "Delta-Gamma", "Delta-Vega", "Rule (a)", "Rule (b)", "Richer rule", "DRL selected", "DRL median"]
    n = len(heads) + 1
    L = [HEADER + "\\begin{tabular}{l" + "c" * len(heads) + "}", "\\toprule",
         " & " + " & ".join(f"\\textbf{{{h}}}" for h in heads) + " \\\\", "\\midrule"]
    for i, c in enumerate(COSTS):
        d = ft[ft.cost == c]
        g = lambda key: d[d.policy.str.startswith(key)].iloc[0].to_dict()
        cols = [g("Delta"), g("DG"), g("DV"), ra[c], g("Rule (b)"), g("Richer rule"), g("DRL pre-commitment, selected"),
                g("DRL pre-commitment, median")]
        best = min(x["VaR95"] for x in cols)
        bc = min(x["CVaR95"] for x in cols)
        if i:
            L.append("\\midrule")
        L += [f"\\multicolumn{{{n}}}{{l}}{{\\textbf{{{cl(c)} Transaction Cost}}}} \\\\", "\\midrule",
              "VaR$_{95\\%}$ & " + " & ".join(("\\textbf{" + f2(x["VaR95"]) + "}" if x["VaR95"] == best else f2(x["VaR95"]))
                                               + f" ({f2(x['VaR95_se'])})" for x in cols) + " \\\\",
              "CVaR$_{95\\%}$ & " + " & ".join(("\\textbf{" + f2(x["CVaR95"]) + "}" if x["CVaR95"] == bc else f2(x["CVaR95"]))
                                                for x in cols) + " \\\\",
              "$\\mathbb{E}[\\text{PnL}]$ & " + " & ".join(f2(x["mean_pnl"]) for x in cols) + " \\\\",
              "$\\mathbb{E}[\\text{TC}]$ & " + " & ".join("0" if x.get("policy") == "Delta" else f2(x["mean_cost"]) for x in cols) + " \\\\"]
    L += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(L) + "\n"


def paired_table():
    pm = pd.read_csv(FIN / "paired_metrics.csv")
    pm = pm[pm.VaR95.isna()]
    L = [HEADER + "\\begin{tabular*}{\\tblwidth}{@{\\extracolsep{\\fill}} ll ccc @{}}", "\\toprule",
         "Cost & DRL selected vs & $\\Delta$VaR$_{95\\%}$ & $\\Delta$CVaR$_{95\\%}$ & $\\Delta\\mathbb{E}[\\text{PnL}]$ \\\\"]
    for c in COSTS:
        L.append("\\midrule")
        for base in ["Delta-Gamma", "Rule (b)", "Richer rule"]:
            key = {"Delta-Gamma": "DG"}.get(base, base)
            r = pm[(pm.cost == c) & pm.policy.str.startswith("DRL selected") & pm.policy.str.endswith("vs " + key)].iloc[0]
            L.append(f"{cl(c) if base == 'Delta-Gamma' else ''} & {base} & {r.dVaR95:+.2f} ({f2(r.dVaR95_se)}) & "
                     f"{r.dCVaR95:+.2f} ({f2(r.dCVaR95_se)}) & {r.dmean_pnl:+.2f} ({f2(r.dmean_pnl_se)}) \\\\")
    L += ["\\bottomrule", "\\end{tabular*}"]
    return "\n".join(L) + "\n"


def robustness_table():
    df = pd.read_csv(FIN / "robustness.csv")
    L = [HEADER + "\\begin{tabular*}{\\tblwidth}{@{\\extracolsep{\\fill}} l ccc ccc @{}}", "\\toprule",
         " & \\multicolumn{3}{c}{DRL $-$ Rule (b), gain in VaR$_{95\\%}$} & \\multicolumn{3}{c}{VaR$_{95\\%}$ at 2\\% cost} \\\\",
         "Market & 0.5\\% & 1\\% & 2\\% & DRL & Rule (b) & DG \\\\", "\\midrule"]
    keys = df[df.cost == 0.02][["parameter", "value"]].values.tolist()
    for i, (p, v) in enumerate(keys):
        sel = lambda c: df[(df.cost == c) & (df.parameter == p) & ((df.value == v) | (pd.isna(v) & df.value.isna()))].iloc[0]
        label = "Base" if p == "base" else ROB[p] % f"{v:g}" + ("$^{*}$" if p == "init_vol" and v == 0.45 else "")
        gains = []
        for c in COSTS:
            r = sel(c)
            g, s = r["DRL selected_gain_vs_rule_b"], r["DRL selected_gain_vs_rule_b_se"]
            txt = f"{g:+.2f} ({f2(s)})"
            gains.append("\\textbf{" + txt + "}" if g < 0 else txt)
        r2 = sel(0.02)
        L.append(f"{label} & " + " & ".join(gains) + f" & {f2(r2['DRL selected_VaR95'])} & {f2(r2['rule_b_VaR95'])} & "
                 f"{f2(r2['DG_VaR95'])} \\\\")
        if i == 0:
            L.append("\\midrule")
    L += ["\\bottomrule", "\\end{tabular*}"]
    return "\n".join(L) + "\n"


def deltacost_table():
    df = pd.read_csv(FIN / "deltacost.csv")
    bps = sorted(df.delta_bp.unique())
    L = [HEADER + "\\begin{tabular*}{\\tblwidth}{@{\\extracolsep{\\fill}} l " + "c" * len(bps) + " @{}}", "\\toprule",
         "Cost on stock trades & " + " & ".join(f"{b:g} bp" for b in bps) + " \\\\"]
    for c in COSTS:
        d = df[df.cost == c].set_index("delta_bp")
        L += ["\\midrule", f"\\multicolumn{{{len(bps) + 1}}}{{l}}{{\\textbf{{{cl(c)} option cost}}}} \\\\"]
        for col, lab in (("DRL selected_VaR95", "DRL selected"), ("DG_VaR95", "Delta-Gamma"), ("rule_b_VaR95", "Rule (b)")):
            L.append(f"{lab} & " + " & ".join(f2(d.loc[b, col]) for b in bps) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular*}"]
    return "\n".join(L) + "\n"


def european_table():
    df = pd.read_csv(FIN / "european_greeks.csv")
    L = [HEADER + "\\begin{tabular*}{\\tblwidth}{@{\\extracolsep{\\fill}} ll cccc @{}}", "\\toprule",
         "Cost & Strategy & American Greeks & European Greeks & Difference VaR$_{95\\%}$ & Difference CVaR$_{95\\%}$ \\\\",
         "\\midrule"]
    for i, r in df.iterrows():
        L.append(f"{cl(r.cost) if r.policy == 'DG' else ''} & {'Delta-Gamma' if r.policy == 'DG' else r.policy} & "
                 f"{f2(r.VaR95_american)} & {f2(r.VaR95_european)} & {r.diff_VaR95:+.2f} ({f2(r.diff_VaR95_se)}) & "
                 f"{r.diff_CVaR95:+.2f} ({f2(r.diff_CVaR95_se)}) \\\\")
    L += ["\\bottomrule", "\\end{tabular*}"]
    return "\n".join(L) + "\n"


def convergence_table():
    z = np.load(FIN / "adi_convergence.npz")
    ref = z["800x400,16steps/day"]
    rows = [("$100\\times50$, 2 steps/day", "100x50,2steps/day"), ("$200\\times100$, 4 steps/day", "200x100,4steps/day"),
            ("$400\\times200$, 8 steps/day (used)", "400x200,8steps/day")]
    L = [HEADER + "\\begin{tabular*}{\\tblwidth}{@{\\extracolsep{\\fill}} l cccc @{}}", "\\toprule",
         "Grid ($s\\times v$, time steps) & Price & Delta & Gamma & Vega \\\\", "\\midrule"]
    for lab, k in rows:
        e = np.abs(z[k] - ref)
        L.append(f"{lab} & " + " & ".join(f"{e[:, q].max():.1e} / {e[:, q].mean():.1e}" for q in range(4)) + " \\\\")
    L += ["\\midrule", "Largest $|$value$|$ in the sample & " + " & ".join(f"{x:.3g}" for x in np.abs(ref).max(0)) + " \\\\",
          "\\bottomrule", "\\end{tabular*}"]
    return "\n".join(L) + "\n"


def seeds_figure():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcdefaults()
    fig, axes = plt.subplots(1, 3, figsize=(13, 3.6), constrained_layout=True)
    for ax, c in zip(axes, COSTS):
        rb = json.load(open(f"review/results/warmstart/richer_rule_params_adi_trading_{c}.json"))[str(c)]["rule_b"]
        for d in sorted(LOGS.glob(f"HestonP_var_spread{c}_seed*_FINAL")):
            v = pd.read_csv(d / "validation.csv")
            v = v[v.episode > 0]
            ax.plot(v.episode / 1000, v.val_VaR95, lw=1, color="#3b6fd4", alpha=0.6)
        ax.axhline(rb["VaR95"], color="#c9412f", lw=1.5, ls="--", label="Rule (b), validation")
        ax.axvline(1.0, color="#888", lw=0.8, ls=":")
        ax.set_title(f"{cl(c).replace(chr(92), '')} cost", fontsize=10)
        ax.set_xlabel("Training episodes (thousands)")
        ax.legend(fontsize=8, loc="upper right")
    axes[0].set_ylabel("Validation VaR$_{95\\%}$")
    (OUT / "figures").mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT / "figures" / "heston_seeds_validation.pdf")


def main():
    (OUT / "tables").mkdir(parents=True, exist_ok=True)
    ra = rule_a(mk(2025), mk(4242))
    json.dump({str(k): v for k, v in ra.items()}, open(FIN / "rule_a.json", "w"), indent=2)
    for name, txt in [("heston", heston_table(ra)), ("paired", paired_table()), ("robustness", robustness_table()),
                      ("deltacost", deltacost_table()), ("european", european_table()), ("convergence", convergence_table())]:
        (OUT / "tables" / f"{name}.tex").write_text(txt)
        print(txt)
    seeds_figure()
    import shutil
    shutil.copy(FIN / "hedge_diff.pdf", OUT / "figures" / "hedge_diff.pdf")


if __name__ == "__main__":
    main()
