"""Early-exercise diagnostic on the FINAL market family (adi_trading, test seed 4242): share of held hedge-put option-days
in the exercise region (in the money and the European price below intrinsic, i.e. early exercise is optimal), r = 2% (main) and r = 0
(contrast), and the early-exercise premium (American - European ADI table, both maturity tau/252) of 60-day puts at
v = 0.09. Writes review/results/paper/tables/early_exercise.tex and review/results/final/early_exercise.md."""
import argparse
from pathlib import Path
import numpy as np
from review.retrain import analysis as A
import train_d4pg as T
from environment.heston_table import HestonAmericanPutTable, HestonTableConfig

HEADER = "% generated by review/final/early_exercise_v2.py -- do not edit\n"
res = {}
for label, extra in (("r2", []), ("r0", ["--r", "0", "--mu", "0"])):
    a = A.block_args("B", ["--market_dir", "../DRL-Hedging-retrain/markets", "--pricing_backend", "adi_trading",
                           "--table_dir", "../DRL-Hedging-retrain/pricing_tables"] + extra)
    m = {k: np.asarray(v) for k, v in A.T.get_market(a, 4242, 8192).items()}
    ae = A.block_args("B", ["--market_dir", "../DRL-Hedging-retrain/markets", "--pricing_backend", "adi_trading_eu",
                            "--table_dir", "../DRL-Hedging-retrain/pricing_tables"] + extra)
    me = {k: np.asarray(v) for k, v in A.T.get_market(ae, 4242, 8192).items()}
    assert np.array_equal(me["S"], m["S"])
    S, cs = m["S"], a.contract_size
    P, T1 = S.shape
    tot, reg, by = 0, 0, {}
    for i in range(T1 - 1):
        K = S[:, i]
        for t in range(i, T1):
            act = ~m["h_inactive"][:, t, i]
            ttm = a.hed_ttm - (t - i)
            if not act.any() or ttm <= 0:
                continue
            price = m["h_price"][:, t, i] / cs
            intr = np.maximum(K - S[:, t], 0.0)
            peu = me["h_price"][:, t, i] / cs
            # exercise region: the European price is below intrinsic, so exercising now is better than holding
            # (the American price then equals intrinsic). Zero at r = 0 in theory.
            ir = act & (intr > 0) & (peu < intr - 1e-6 * K)
            tot += act.sum(); reg += ir.sum()
            n0, r0 = by.get(ttm, (0, 0)); by[ttm] = (n0 + act.sum(), r0 + ir.sum())
    u = T.make_utils(argparse.Namespace(**{**vars(a), "spread": 0.0}), 1, 8)
    cfg = HestonTableConfig.from_utils(u)
    am = HestonAmericanPutTable.load_or_build_adi(cfg, table_dir="../DRL-Hedging-retrain/pricing_tables", quantlib_maturity=False)
    eu = HestonAmericanPutTable.load_or_build_adi(cfg, table_dir="../DRL-Hedging-retrain/pricing_tables", quantlib_maturity=False, european=True)
    prem = {}
    for mny in (1.0, 0.8):
        pa = am.evaluate(np.array([mny]), np.array([1.0]), np.array([60]), np.array([0.3]))[0][0]
        pe = eu.evaluate(np.array([mny]), np.array([1.0]), np.array([60]), np.array([0.3]))[0][0]
        prem[mny] = (pa - pe) / pa
    top_ttm = max(by, key=lambda k: by[k][1] / by[k][0])
    res[label] = dict(share=reg / tot, top=by[top_ttm][1] / by[top_ttm][0], top_ttm=top_ttm, prem_atm=prem[1.0],
                      prem_08=prem[0.8], n=int(tot))
    print(label, res[label], flush=True)
pct = lambda x: f"{100 * x:.2f}\\%"
rows = [("Option-days in exercise region", pct(res["r0"]["share"]), pct(res["r2"]["share"])),
        ("Largest share by days to expiry", f"{100 * res['r0']['top']:.1f}\\%", f"{100 * res['r2']['top']:.1f}\\%"),
        ("Premium / price, ATM, 60 d", pct(res["r0"]["prem_atm"]), pct(res["r2"]["prem_atm"])),
        ("Premium / price, $S/K=0.8$, 60 d", pct(res["r0"]["prem_08"]), pct(res["r2"]["prem_08"]))]
L = [HEADER + "\\begin{tabular*}{\\tblwidth}{@{\\extracolsep{\\fill}} l cc @{}}", "\\toprule",
     " & $r=0$ & $r=2\\%$ \\\\", "\\midrule"] + [f"{a} & {b} & {c} \\\\" for a, b, c in rows] + ["\\bottomrule", "\\end{tabular*}"]
Path("review/results/paper/tables/early_exercise.tex").write_text("\n".join(L) + "\n")
Path("review/results/final/early_exercise.md").write_text("# Early exercise (adi_trading, test 4242)\n\n" + "\n".join(
    f"- {k}: {v}" for k, v in res.items()) + "\n")
print("\n".join(L))
