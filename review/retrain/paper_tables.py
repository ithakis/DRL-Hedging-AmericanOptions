"""Write the LaTeX tabulars of the paper from the result files of analysis.py.

Only the numbers are generated (one `tabular` per table). Caption, label and notes stay in main.tex,
which includes each file with \\input in place of the hand-typed tabular:

    PYTHONPATH=. python review/retrain/paper_tables.py          # -> review/results/paper/tables/*.tex

Inputs (all in review/results/retrain): baselines_{A,B}.json, main_{A,B}.csv, deltacost_B.csv,
robustness.csv, early_exercise_by_day.csv, early_exercise_premium.csv.
Bold = lowest VaR95 in the row (dark blue bold, as in the first version of the paper). The robustness
table also gives the paired difference RL - rule (b) with its paired bootstrap standard error.
"""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "review" / "results" / "retrain"
OUT = ROOT / "review" / "results" / "paper" / "tables"
COSTS = [0.005, 0.01, 0.02]
HEADER = "% generated by review/retrain/paper_tables.py from review/results/retrain -- do not edit\n"


def f2(x):
    return f"{x:.2f}"


def cost_label(c):
    return f"{c * 100:g}\\%"


def bold(s):
    """Best value: dark blue bold, the style of the result tables in the first version."""
    return "\\textbf{\\textcolor{darkblue}{" + s + "}}"


def var_cells(vals, ses):
    """VaR cells 'v (se)', the lowest value in bold."""
    best = min(vals)
    return [(bold(f2(v)) if v == best else f2(v)) + f" ({f2(s)})" for v, s in zip(vals, ses)]


def main_table(blk):
    base = json.load(open(RES / f"baselines_{blk}.json"))
    df = pd.read_csv(RES / f"main_{blk}.csv")
    heston = blk == "B"
    names = ["delta", "DG"] + (["DV"] if heston else []) + ["rule_a_VaR95", "rule_b_VaR95"]
    heads = ["Delta", "Delta-Gamma"] + (["Delta-Vega"] if heston else []) + ["Rule (a)", "Rule (b)",
                                                                             "RL selected", "RL median"]
    ncol = len(heads) + 1
    L = [HEADER + "\\begin{tabular}{l" + "c" * len(heads) + "}", "\\toprule",
         " & " + " & ".join(f"\\textbf{{{h}}}" for h in heads) + " \\\\", "\\midrule"]
    for i, c in enumerate(COSTS):
        b = base[f"{c}_0"]
        rl = [df[(df.spread == c) & (df.agent == a)].iloc[0] for a in ("selected", "median")]
        cols = [b[n] for n in names] + [r.to_dict() for r in rl]
        tc = ["0" if n == "delta" else f2(b[n]["mean_cost"]) for n in names] + [f2(r["mean_cost"]) for r in cols[-2:]]
        if i:
            L.append("\\midrule")
        L += [f"\\multicolumn{{{ncol}}}{{l}}{{\\textbf{{{cost_label(c)} Transaction Cost}}}} \\\\", "\\midrule",
              "VaR$_{95\\%}$  & " + " & ".join(var_cells([x["VaR95"] for x in cols], [x["VaR95_se"] for x in cols]))
              + " \\\\",
              "CVaR$_{95\\%}$ & " + " & ".join(f2(x["CVaR95"]) for x in cols) + " \\\\",
              "$\\mathbb{E}[\\text{TC}]$ & " + " & ".join(tc) + " \\\\"]
    L += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(L) + "\n"


def deltacost_table():
    df = pd.read_csv(RES / "deltacost_B.csv")
    bps = sorted(df.delta_bp.unique())
    L = [HEADER + "\\begin{tabular*}{\\tblwidth}{@{\\extracolsep{\\fill}} l " + "c" * len(bps) + " @{}}", "\\toprule",
         "Cost on stock trades & " + " & ".join(f"{b} bp" for b in bps) + " \\\\"]
    for c in COSTS:
        d = df[df.spread == c].set_index("delta_bp")
        L += ["\\midrule", f"\\multicolumn{{{len(bps) + 1}}}{{l}}{{\\textbf{{{cost_label(c)} option cost}}}} \\\\"]
        for col, lab in (("RL_VaR95", "RL selected "), ("DG_VaR95", "Delta-Gamma "), ("rule_b_VaR95", "Rule (b)    ")):
            L.append(f"{lab} & " + " & ".join(f2(d.loc[b, col]) for b in bps) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular*}"]
    return "\n".join(L) + "\n"


def early_table():
    day = pd.read_csv(RES / "early_exercise_by_day.csv")
    prem = pd.read_csv(RES / "early_exercise_premium.csv")
    sets = {"r0": "r=0 (contrast)", "r2": "r=2% (main)"}
    tot = day.groupby("setting")[["n_active", "n_exercise_region"]].sum()
    by = day.groupby(["setting", "ttm"])[["n_active", "n_exercise_region"]].sum()
    share = lambda s: tot.loc[s, "n_exercise_region"] / tot.loc[s, "n_active"]
    top = lambda s: (by.loc[s, "n_exercise_region"] / by.loc[s, "n_active"]).max()
    rel = lambda r, m: prem[(prem.r == r) & (prem.ttm == 60) & (prem.moneyness.round(2) == m)].rel.iloc[0]
    pct = lambda x: f"{100 * x:.2f}\\%"
    rows = [("Option-days in exercise region", pct(share(sets["r0"])), pct(share(sets["r2"]))),
            ("Largest share by days to expiry", f"{100 * top(sets['r0']):.1f}\\%", f"{100 * top(sets['r2']):.1f}\\%"),
            ("Premium / price, ATM, 60 d", pct(rel(0.0, 1.0)), pct(rel(0.02, 1.0))),
            ("Premium / price, $S/K=0.8$, 60 d", pct(rel(0.0, 0.8)), pct(rel(0.02, 0.8)))]
    L = [HEADER + "\\begin{tabular*}{\\tblwidth}{@{\\extracolsep{\\fill}} l cc @{}}", "\\toprule",
         " & $r=0$ & $r=2\\%$ \\\\", "\\midrule"] + [f"{a} & {b} & {c} \\\\" for a, b, c in rows]
    L += ["\\bottomrule", "\\end{tabular*}"]
    return "\n".join(L) + "\n"


ROB_LABEL = {"init_vol": "$\\sqrt{v_0}=%s$", "volvol": "$\\xi=%s$", "rho": "$\\rho=%s$", "theta": "$\\theta=%s$",
             "kappa": "$\\kappa=%s$"}


def robustness_table():
    df = pd.read_csv(RES / "robustness.csv")
    keys = ["delta", "DG", "DV", "rule_a", "rule_b", "RL"]
    heads = ["Delta", "DG", "DV", "Rule (a)", "Rule (b)", "RL", "RL $-$ Rule (b)", "RL $\\mathbb{E}[\\text{TC}]$"]
    L = [HEADER + "\\begin{tabular*}{\\tblwidth}{@{\\extracolsep{\\fill}} l " + "c" * len(heads) + " @{}}",
         "\\toprule", "Market & " + " & ".join(heads) + " \\\\", "\\midrule"]
    for i, r in df.iterrows():
        label = "Base" if r.parameter == "base" else ROB_LABEL[r.parameter] % f"{r.value:g}"
        v = {k: r[f"{k}_VaR95"] for k in keys}
        best = min(v.values())
        cell = {k: (bold(f2(x)) if x == best else f2(x)) for k, x in v.items()}
        cell["RL"] += f" ({f2(r.RL_VaR95_se)})"
        diff = f"${-r.gain_vs_rule_b:+.2f}$ ({f2(r.gain_vs_rule_b_se)})"
        L.append(f"{label} & " + " & ".join(cell[k] for k in keys) + f" & {diff} & {f2(r.RL_mean_cost)} \\\\")
        if i == 0:
            L.append("\\midrule")
    L += ["\\bottomrule", "\\end{tabular*}"]
    return "\n".join(L) + "\n"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    tables = {"gbm": lambda: main_table("A"), "heston": lambda: main_table("B"), "deltacost": deltacost_table,
              "early_exercise": early_table, "robustness": robustness_table}
    for name, fn in tables.items():
        (OUT / f"{name}.tex").write_text(fn())
        print("wrote", (OUT / f"{name}.tex").relative_to(ROOT))


if __name__ == "__main__":
    main()
